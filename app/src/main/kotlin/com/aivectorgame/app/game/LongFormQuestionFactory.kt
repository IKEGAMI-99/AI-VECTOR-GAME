    fun create(seed: Int): Question {
        val random = Random(seed)
        val scenario = scenarios.random(random)
        val prompt = scenario.prompts.random(random)
        val choices = scenario.continuations.shuffled(random).take(6)

        // Demo scores mimic average per-token log probabilities. Higher (less negative) wins.
        val demoScores = choices.indices
            .map { -1.25f - random.nextFloat() * 2.6f }
            .toMutableList()
        if (demoScores.isNotEmpty()) {
            val preferred = random.nextInt(demoScores.size)
            demoScores[preferred] = -0.75f - random.nextFloat() * 0.35f
        }

        return Question(
            prompt = prompt,
            choices = choices,
            demoScores = demoScores,
            seed = seed,
        )
    }
